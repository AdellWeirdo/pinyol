def cart(frame: int) -> list[str]:
    """The tub over two wheels whose spokes turn (+ then x)."""
    w = WHEELS[f"w{frame}"]
    rows = [list(r) for r in CART_BODY]
    for wx in (1, 10):
        for y, r in enumerate(w):
            for x, c in enumerate(r):
                if c == "X":
                    rows[11 + y][wx + x] = "X"
    return ["".join(r) for r in rows]


CART = {"vagoneta_0": cart(0), "vagoneta_1": cart(1)}


def register(ART) -> None:
    ART.sheet("ENEMY", 16, 16)
    for group in (ROBOT, BAT, SPIDER, RAT, FLAME, EYE, CART):
        for n, r in group.items():
            ART.sprite("ENEMY", n, r)
