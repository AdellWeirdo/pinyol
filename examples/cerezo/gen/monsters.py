import gbart as g  # noqa: E402
from gbart import ART  # noqa: E402


def P(text: str, w: int = 16, h: int = 16) -> g.Pic:
    """A w x h picture from text rows (indentation stripped), checked."""
    return g.pic([ln.strip() for ln in text.strip("\n").split("\n")], w, h)


def B(text: str) -> g.Pic:
    """A part of any size (rows padded with see-through to the longest), to place with `at`."""
    rows = [ln.strip() for ln in text.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    return g.pic([r.ljust(w, ".") for r in rows])


def at(base: g.Pic, part: g.Pic, x: int, y: int) -> g.Pic:
    return g.overlay(base, part, x, y)


def frame(*parts: tuple, w: int = 16, h: int = 16) -> g.Pic:
    """A frame built from (part, x, y) laid in order (the last on top)."""
    p = g.blank(w, h)
    for part, x, y in parts:
        p = at(p, part, x, y)
    return p


