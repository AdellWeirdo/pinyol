"""ui_fx: the status bar, the dialogue window, the pause menu's tiles, the items, the pickups and the effects of Cerezo.

Tileset "ui" (the UI layer, see core/ui.lua):
* 8x8 tiles (bank 0): hud_bg, hud_bg_low (the bar's lower row: paper with the bar's bottom line in its last row),
  heart_full/half/empty, digit_0..9 and icon_cherry, icon_pinyol (made for the bar's LOWER row: they carry the bottom
  line), digit_top_0..9, x, slash, icon_key, icon_bosskey, icon_map, icon_compass, icon_pit, icon_pit_empty (no line:
  the bar's top row and the menu), dlg_tl dlg_t dlg_tr dlg_l dlg_fill dlg_r dlg_bl dlg_b dlg_br dlg_arrow, menu_bg,
  menu_line.
* 16x16 metatiles: item boxes (bank 5) box_empty item_pala item_tirachinas item_linterna (the bar's: the button letter
  in the top-left corner where the frame stops short of it, last row = the bar's line) and box_pala box_tirachinas
  box_linterna box_none (the menu's: closed frame, no letter); the island map (bank 0) map_unseen + nine screens.
Sheets: ITEMS16 (16x16, bank 5), PROPS (16x16, bank 6), UI8 (8x8, bank 5; effects in their brief banks).

Decisions: heavy ink (3) on paper (0); digits are 5x5 with two-pixel stems like the game's "ps" font; hearts are a
7x6 shaded heart (half = left half filled); the dialogue frame is the classic double line (outer, 1 px gap, inner)
with rounded corners and a one-pixel paper halo so it stays clear over water; the map is one 48x48 island cut in nine
along maps_overworld.py's 3x3 layout. shot_pinyol faces right (the side-view rule).
"""
