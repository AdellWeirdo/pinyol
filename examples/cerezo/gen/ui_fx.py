def digit_tile(glyph: list[str], x0: int = 1, y0: int = 1, line: bool = True) -> g.Pic:
    rows = [list(PAPER) for _ in range(8)]
    for y, r in enumerate(glyph):
        for x, c in enumerate(r):
            if c == "#":
                rows[y0 + y][x0 + x] = "3"
    if line:
        rows[7] = list(LINE)
    return g.pic(["".join(r) for r in rows], 8, 8)


