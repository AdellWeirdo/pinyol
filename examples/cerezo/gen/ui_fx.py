PLACE = {"pala": ((2, 2), (2, 2)), "tirachinas": ((2, 2), (3, 2)), "linterna": ((2, 2), (2, 3))}


def box(item: str | None, letter: str | None) -> g.Pic:
    p = frame16(letter)
    if item is not None:
        icon = {"pala": ICON_PALA, "tirachinas": ICON_TIRACHINAS, "linterna": ICON_LINTERNA}[item]
        x, y = PLACE[item][0 if letter is None else 1]
        p = g.overlay(p, icon, x, y)
    return p


