# ============================================================================ item boxes: 16x16 metatiles
LETTER = {"A": [".3.", "3.3", "333", "3.3", "3.3"], "B": ["33.", "3.3", "33.", "3.3", "33."]}


def frame16(letter: str | None) -> g.Pic:
    """An item box. With a letter it is the bar's: the button's letter sits in the top-left corner where the frame
    stops short of it, and the last row is the bar's own bottom line. Without, the menu's: a closed rounded frame."""
    if letter is None:
        rows = ["0333333333333330"] + ["3000000000000003"] * 14 + ["0333333333333330"]
        return g.pic(rows, 16, 16)
    rows = ["0000033333333300", "0000000000000030"] + ["0000000000000003"] * 5 + ["3000000000000003"] * 8 + \
        ["3333333333333333"]
    p = g.pic(rows, 16, 16)
    for y, r in enumerate(LETTER[letter]):
        for x, c in enumerate(r):
            if c == "3":
                p[y][x] = 3
    return p


