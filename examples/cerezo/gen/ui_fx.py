def P(text: str, w: int, h: int) -> g.Pic:
    """Text rows, indented freely, to a w x h picture (checked)."""
    return g.pic([ln.strip() for ln in text.strip().split("\n")], w, h)


def P8(text: str) -> g.Pic:
    return P(text, 8, 8)


def P16(text: str) -> g.Pic:
    return P(text, 16, 16)


# ============================================================================ the status bar: 8x8 tiles
# Row 0 of the bar (y 0-7) holds the hearts; row 1 (y 8-15) the counters and ends in the bar's bottom line, so every
# tile made for row 1 carries that line in its last row and the line runs unbroken under icons and digits.
PAPER = "00000000"
LINE = "33333333"


def low(rows7: str) -> g.Pic:
    """A tile of the bar's lower row: seven rows of picture and the bar's bottom line."""
    rows = [ln.strip() for ln in rows7.strip("\n").split("\n")]
    return g.pic(rows + [LINE], 8, 8)


