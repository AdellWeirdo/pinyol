def cut(p: g.Pic, prefix: str, bank: int) -> None:
    """A big picture into 16x16 metatiles named prefix_<row>_<col> (or prefix_<col> for a strip one tile tall)."""
    rows, cols = len(p) // 16, len(p[0]) // 16
    for r in range(rows):
        for c in range(cols):
            name = f"{prefix}_{r}_{c}" if rows > 1 else f"{prefix}_{c}"
            ART.meta(UI, name, g.crop(p, c * 16, r * 16, 16, 16), bank=bank)


