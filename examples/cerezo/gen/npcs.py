def _backs() -> list[g.Pic]:
    """16x16 grounds to stand the people on: grass (tone 0 with tufts), a light floor, a dark floor, the darkest."""
    grass = g.blank(16, 16, 0)
    for x, y in ((3, 4), (2, 5), (4, 5), (11, 11), (10, 12), (12, 12)):
        grass[y][x] = 2
    light = g.blank(16, 16, 1)
    for x in range(16):
        light[15][x] = 2
    dark = g.blank(16, 16, 2)
    for x, y in ((3, 3), (11, 9), (6, 13)):
        dark[y][x] = 3
    ink = g.blank(16, 16, 3)
    return [grass, light, dark, ink]


def _hero() -> dict[str, g.Pic]:
    try:
        import chars
        return {"down_0": chars.DOWN_0, "up_0": chars.UP_0, "side_0": chars.SIDE_0, "side_1": chars.SIDE_1}
    except Exception:  # the hero's module is someone else's and may be mid-edit
        return {}


def _board(pics, cols: int, sc: int, tones):
    from PIL import Image, ImageDraw
    gap = 6
    rows = (len(pics) + cols - 1) // cols
    cw, ch = 16 * sc + gap, 16 * sc + gap + 12
    img = Image.new("RGB", (cols * cw + gap, rows * ch + gap), (60, 60, 70))
    d = ImageDraw.Draw(img)
    for i, (n, p) in enumerate(pics):
        x0, y0 = gap + (i % cols) * cw, gap + (i // cols) * ch
        img.paste(g.to_image(p, tones, sc, (112, 128, 168)), (x0, y0))
        for t in range(17):
            c = (96, 110, 150) if t % 8 else (230, 80, 80)
            d.line([(x0 + t * sc, y0), (x0 + t * sc, y0 + 16 * sc)], fill=c)
            d.line([(x0, y0 + t * sc), (x0 + 16 * sc, y0 + t * sc)], fill=c)
        d.text((x0, y0 + 16 * sc + 1), n[:24], fill=(230, 230, 230))
    return img


def _crowd(line: list[g.Pic], tones, scales=(1, 2, 3)):
    from PIL import Image
    strips = [g.side_by_side(*[g.overlay(b, p) for p in line]) for b in _backs()]
    full = g.paste_rows(*strips)
    parts = [g.to_image(full, tones, s) for s in scales]
    sheet = Image.new("RGB", (sum(p.width for p in parts) + 8 * (len(parts) + 1), max(p.height for p in parts) + 16), (60, 60, 70))
    x = 8
    for p in parts:
        sheet.paste(p, (x, 8))
        x += p.width + 8
    return sheet


def preview(tag: str = "r", who: str | None = None) -> None:
    """art/npcs_<tag>_<id>.png: every frame of a character zoomed (DMG, POCKET) and on four grounds at 1x, 2x, 4x;
    art/npcs_<tag>_crowd_*.png: everyone's down_0 next to the hero."""
    import palettes
    from PIL import Image

    out = g.ART_DIR
    hero = _hero()
    for cid, fr, _ in PEOPLE:
        if who is not None and cid != who:
            continue
        keys = VIEWS + [k for k in fr if k not in VIEWS]
        pics = [(k, fr[k]) for k in keys]
        extra = [hero[k] for k in ("down_0", "side_0") if k in hero]
        parts = [_board(pics, len(pics), 8, palettes.DMG), _board(pics, len(pics), 8, palettes.POCKET),
                 _crowd([fr[k] for k in keys] + extra, palettes.DMG, (1, 2, 4)),
                 _crowd([fr[k] for k in keys] + extra, palettes.POCKET, (1, 2, 4))]
        img = Image.new("RGB", (max(p.width for p in parts), sum(p.height for p in parts)), (40, 40, 48))
        y = 0
        for part in parts:
            img.paste(part, (0, y))
            y += part.height
        img.save(out / f"npcs_{tag}_{cid}.png")
    if who is None:
        line = ([hero["down_0"]] if "down_0" in hero else []) + [fr["down_0"] for _, fr, _ in PEOPLE]
        for label, tones in (("dmg", palettes.DMG), ("pocket", palettes.POCKET)):
            _crowd(line, tones).save(out / f"npcs_{tag}_crowd_{label}.png")


if __name__ == "__main__":
    preview(sys.argv[1] if len(sys.argv) > 1 else "r", sys.argv[2] if len(sys.argv) > 2 else None)
