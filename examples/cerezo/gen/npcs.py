def frames() -> list[tuple[str, g.Pic, int]]:
    """Every frame in sheet order: each character's five views, then its extra poses."""
    out = []
    for who, fr, bank in PEOPLE:
        for v in VIEWS + [k for k in fr if k not in VIEWS]:
            out.append((f"{who}_{v}", fr[v], bank))
    return out


def register() -> None:
    sh = ART.sheet("NPC", 16, 16, bank=1)
    for name, p, bank in frames():
        sh.add(name, p, bank=bank)


register()


