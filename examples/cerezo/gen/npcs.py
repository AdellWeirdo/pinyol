def P(text: str) -> g.Pic:
    """A 16x16 picture from text rows, checked."""
    return g.pic(text, 16, 16)


def edit(p: g.Pic, rows: dict[int, str]) -> g.Pic:
    """A copy of `p` with some rows redrawn (each a full 16-pixel row)."""
    out = [r[:] for r in p]
    for y, text in rows.items():
        out[y] = g.pic([text], 16, 1)[0]
    return out


def bob(p: g.Pic, cut: int) -> g.Pic:
    """Breathing: everything above row `cut` sinks one pixel and row `cut` (a plain row of the body) is squeezed out."""
    return [[-1] * 16] + [r[:] for r in p[:cut]] + [r[:] for r in p[cut + 1:]]


def lean(p: g.Pic, upto: int, dx: int) -> g.Pic:
    """Rows 0..upto-1 moved sideways by dx (the scarecrow's sway)."""
    out = [r[:] for r in p]
    moved = g.shift(p, dx, 0)
    for y in range(upto):
        out[y] = moved[y]
    return out


