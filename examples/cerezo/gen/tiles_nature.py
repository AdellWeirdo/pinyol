def _map_screens(out) -> None:
    """The real screens of the overworld that hold these tiles, with every module loaded (another artist's module that
    does not load is skipped; a name nobody draws yet is a hatched stub)."""
    import palettes
    try:
        import build
        import rules
        sys.modules.setdefault("tiles_nature", sys.modules[__name__])  # run as a script: do not register twice
        argv = list(sys.argv)
        sys.argv.append("--lenient")
        build.load_modules()
        sys.argv[:] = argv
        rules.apply()
        build.stub_missing()
        import maps_overworld as mo
    except Exception as e:
        print("no map previews:", type(e).__name__, e)
        return
    area = mo.OW
    metas = ART.metas[area.tileset]
    names = area.names(metas, lenient=True)
    for (sx, sy), label in (((1, 0), "monte"), ((2, 0), "mirador"), ((1, 1), "plaza"), ((0, 0), "bosque"), ((0, 1), "huerto")):
        sub = [row[sx * 15:(sx + 1) * 15] for row in names[sy * 9:(sy + 1) * 9]]
        _save_pair(g.scene_image(sub, metas, palettes.DMG, 3), g.scene_image(sub, metas, palettes.POCKET, 3),
                   out / f"nature_map_{label}.png")
        alt = [[n.replace("cavedoor", "caveopen").replace("cherry_dead", "cherry_bloom") for n in row] for row in sub]
        if alt != sub:
            _save_pair(g.scene_image(alt, metas, palettes.DMG, 3), g.scene_image(alt, metas, palettes.POCKET, 3),
                       out / f"nature_map_{label}_after.png")


def preview() -> None:
    import palettes
    from PIL import Image, ImageDraw

    out = g.ART_DIR
    out.mkdir(exist_ok=True)
    try:
        import tiles_terrain  # noqa: F401  (the grass, paths and rocks, to see these tiles among them)
    except Exception as e:  # another artist's module mid-edit: the previews fall back on the grass copy
        print("preview without tiles_terrain:", e)
    metas = dict(ART.metas[SET])
    metas.setdefault("grass_a", g.Metatile("grass_a", GRASS_COPY, None, (), 0, 0))
    hero = _hero()
    names = [n for n in MINE]
    for label, tones in (("dmg", palettes.DMG), ("pocket", palettes.POCKET)):
        cols, sc, cw, ch = 10, 4, 16 * 4 + 8, 16 * 4 + 18
        rows = (len(names) + cols - 1) // cols
        img = Image.new("RGB", (cols * cw + 8, rows * ch + 8), (200, 200, 200))
        d = ImageDraw.Draw(img)
        for i, n in enumerate(names):
            x, y = 8 + (i % cols) * cw, 8 + (i // cols) * ch
            img.paste(g.scene_image([[n]], metas, tones, sc), (x, y))
            d.text((x, y + 16 * sc + 1), n[:13], fill=(0, 0, 0))
        img.save(out / f"nature_tiles_{label}.png")
    _test_scenes(metas, out, hero)
    if "--maps" in sys.argv:
        _map_screens(out)


if __name__ == "__main__":
    preview()
