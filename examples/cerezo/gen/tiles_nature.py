def B(s: str, w: int | None = None, h: int | None = None) -> g.Pic:
    """Text rows, indented freely, to a picture (checked to be w x h when given)."""
    return g.pic([ln.strip() for ln in s.strip("\n").split("\n")], w, h)


def T(s: str) -> g.Pic:
    return B(s, 16, 16)


