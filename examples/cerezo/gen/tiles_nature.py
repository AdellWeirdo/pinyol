def big_tree(prefix: str, front: g.Pic, trunk: g.Pic, shade: g.Pic) -> None:
    """A 2x2 tree: top cells plain grass with the crown in front; bottom cells the trunk, roots and shadow (solid)."""
    ground = ground_of(shade, trunk, w=32, h=32)
    gc, fc = cells(ground), cells(front)
    for (r, c), name in (((0, 0), "tl"), ((0, 1), "tr"), ((1, 0), "bl"), ((1, 1), "br")):
        ART.meta(SET, f"{prefix}_{name}", grass() if r == 0 else gc[(r, c)], front=None if empty(fc[(r, c)]) else fc[(r, c)],
                 flags=() if r == 0 else ("solid",), bank=3)


def cherry(prefix: str, front: g.Pic, obj: g.Pic, shade: g.Pic) -> None:
    ground = ground_of(shade, obj, w=64, h=64)
    gc, fc = cells(ground), cells(front)
    for (r, c), gp in gc.items():
        fp = fc[(r, c)]
        ART.meta(SET, f"{prefix}_{r}_{c}", gp, front=None if empty(fp) else fp,
                 flags=("solid",) if (r, c) in CHERRY_SOLID else (), bank=7)


