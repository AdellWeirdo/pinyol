def grass() -> g.Pic:
    m = ART.metas.get(SET, {}).get("grass_a")
    return [row[:] for row in (m.ground if m is not None else GRASS_COPY)]


def _tufts(p: g.Pic, base: int = 0) -> list[list[tuple[int, int]]]:
    """Groups of touching pixels that are not the grass's base tone (its tufts and flowers)."""
    h, w = len(p), len(p[0])
    seen, out = set(), []
    for y in range(h):
        for x in range(w):
            if p[y][x] != base and (x, y) not in seen:
                stack, comp = [(x, y)], []
                seen.add((x, y))
                while stack:
                    cx, cy = stack.pop()
                    comp.append((cx, cy))
                    for dx in (-1, 0, 1):
                        for dy in (-1, 0, 1):
                            nx, ny = cx + dx, cy + dy
                            if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in seen and p[ny][nx] != base:
                                seen.add((nx, ny))
                                stack.append((nx, ny))
                out.append(comp)
    return out


def ground_of(*layers: g.Pic, w: int = 16, h: int = 16, ox: int = 0, oy: int = 0, clear: int = 1) -> g.Pic:
    """Grass with pictures laid over it ('.' lets the grass through). A tuft of grass that would touch what is drawn
    (within `clear` pixels) is taken out first, so no half tuft sticks to an outline. Big pictures are cut later:
    `ox, oy` is where this w x h piece sits in the tiling of grass (the grass repeats every 16 pixels)."""
    gr = grass()
    base = [[gr[(y + oy) % 16][(x + ox) % 16] for x in range(w)] for y in range(h)]
    drawn = {(x, y) for p in layers for y, row in enumerate(p) for x, v in enumerate(row) if v >= 0}
    near = {(x + dx, y + dy) for x, y in drawn for dx in range(-clear, clear + 1) for dy in range(-clear, clear + 1)}
    for comp in _tufts(base):
        if any(c in near for c in comp):
            for x, y in comp:
                base[y][x] = 0
    for p in layers:
        base = g.overlay(base, p)
    return base


def cells(p: g.Pic) -> dict[tuple[int, int], g.Pic]:
    """A big picture cut into 16x16 cells: {(row, col): picture}."""
    return {(r, c): g.crop(p, c * 16, r * 16, 16, 16) for r in range(len(p) // 16) for c in range(len(p[0]) // 16)}


def empty(p: g.Pic | None) -> bool:
    return p is None or all(v < 0 for row in p for v in row)


def paint(rows: str, mats: dict, w: int, h: int, outline: int | None = 3) -> g.Pic:
    """gbart.paint on indented text, checked to w x h."""
    return g.as_pic(g.paint([ln.strip() for ln in rows.strip("\n").split("\n")], mats, outline), w, h)


def cutout(p: g.Pic) -> g.Pic:
    """A picture drawn on tone-0 grass made see-through where that grass touches the edges (flood fill), so it can be
    laid on the live grass with `ground_of`."""
    h, w = len(p), len(p[0])
    out = [row[:] for row in p]
    stack = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while stack:
        x, y = stack.pop()
        if 0 <= x < w and 0 <= y < h and out[y][x] == 0:
            out[y][x] = -1
            stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return out


def shadow(w: int, h: int, cx: float, cy: float, rx: float, ry: float, tone: int = 2, solid: float = 0.0) -> g.Pic:
    """A soft shadow on the ground: an ellipse dithered in `tone` (solid in its inner `solid` part)."""
    p = g.blank(w, h)
    for y in range(h):
        for x in range(w):
            d = ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2
            if d <= 1 and (d <= solid or (x + y) % 2 == 0):
                p[y][x] = tone
    return p


