"""chars: Brote, the hero of Cerezo (the player), and what his tools draw. Sheets HERO, HEROX and TOOLFX.

HERO (16x16, bank 0): the walk in three views (down, up, side; side faces right and the engine mirrors it for left),
each `_0` stand, `_1` step A, `_2` step B (the game plays 0,1,0,2), then blink, get_item, hurt_*, die_0..3, push_*,
fall, sleep, sit_0/1.
HEROX (32x32, bank 0): the poses with a tool. A 16x16 body is placed with `on32` so that pixel (8,8) of the small frame
is pixel (16,16) of the big one: the game swaps one for the other and the hero does not jump.
TOOLFX (16x16, bank 6): the swish of the pala, earth and grass that fly, the spark of a hit.

Design (the decisions, so the other artists can match them):
* Proportions: head 9 rows (straw-hat dome rows 1-3, band row 4, brim rows 4-6, face rows 7-9), body 6 rows (10-15).
  Stand frames leave row 0 empty: on a step the whole body rises 1 px (a springy kid's walk) and the legs stretch, so
  the planted boot reaches row 15 and the lifted one stays 1 px up. Bodies are centred on x 8.
* Tones: the hat is the light mass (dome 1 with a 0 highlight top-left and a 2 shade right; band 2; brim top 0 and a
  tone 2 underside that is also the shadow on the forehead), the face is 0 with tone 2 hair at the temples, eyes are
  2 px tall tone 3 dots; the tunic is the dark mass (2, with tone 1 light on the left shoulder and a tone 1 strap);
  belt 3 with a tone 1 buckle; hands 0; boots 3 with a tone 2 shine. Light and dark halves keep him readable on light
  grass and on dark floors in both palettes. Selective outline: tone 3 round the silhouette, tone changes inside.
* The leaf: an almond leaf tucked in the band, on the right in the front view; the back view mirrors it (it is on his
  left side) and the side view shows it at the back of the hat, so it is always part of the silhouette.
* The brim droops: its ends hang one pixel by the temples (rows 6-7), a straw hat rather than a flat plate.
* The face: eyes sit low (rows 8-9, the younger look) and the chin rests directly on the tunic (0 against 2 needs no
  ink line). Without the hat (sleep) his hair has a sprout-shaped cowlick: that is why he is called Brote.
* die_3 is the comic KO: flat on his back, arms and legs out, the hat fallen over his face.
* HEROX frames are full 32x32 pictures, built from the 16x16 bodies with `on32` (heads identical to the walk frames,
  or 1 px lower for the crouch of dig) and the tool drawn on top. The pala: a T-grip, a 1 px tone 2 handle with a
  tone 3 shadow side, a flat-topped blade with a socket and a rounded point (tone 0, shade 1, outline 3) so it reads
  as a shovel and not a sword; at the strike the blade is 12-13 px from the body's centre, as far as the frame allows.
* TOOLFX: swishes have a tone 0 rim and a tone 2 inner edge and tail, so they read on tone 0 grass and on dark
  floors; cut grass is tone 1/2 with a tone 3 cut end for the same reason.
"""
